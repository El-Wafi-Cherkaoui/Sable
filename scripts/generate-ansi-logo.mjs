import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(__dirname, "..");
const sourcePath = path.join(rootDirectory, "assets", "sable-logo.png");
const outputPath = path.join(rootDirectory, "src", "generated", "sable-logo-ansi.ts");
const logoWidth = 20;
const logoHeight = 8;
const contentLumaThreshold = 25;
const cropMarginRatio = 0.05;
const blockThreshold = 42;
const brailleDots = [1, 2, 4, 64, 8, 16, 32, 128];
const ansiPalette = [
  { r: 0, g: 0, b: 0, foreground: 30, background: 40 },
  { r: 192, g: 192, b: 192, foreground: 37, background: 47 },
  { r: 128, g: 128, b: 128, foreground: 90, background: 100 },
  { r: 255, g: 255, b: 255, foreground: 97, background: 107 },
];
const blackPixel = { r: 0, g: 0, b: 0, a: 255 };

const contentBounds = await findContentBounds(sourcePath);
const { data, info } = await sharp(sourcePath)
  .extract(contentBounds)
  .resize({
    width: logoWidth * 2,
    height: logoHeight * 4,
    fit: "fill",
  })
  .ensureAlpha()
  .normalise()
  .sharpen({ sigma: 1 })
  .raw()
  .toBuffer({ resolveWithObject: true });

const rows = [];

for (let y = 0; y < info.height; y += 4) {
  let row = "";

  for (let x = 0; x < info.width; x += 2) {
    row += renderBrailleCell(x, y);
  }

  rows.push(`${row}\x1b[0m`);
}

const contents = `// This file is generated by scripts/generate-ansi-logo.mjs. Do not edit by hand.
export const sableLogoAnsi = ${JSON.stringify(rows, null, 2)};
export const sableLogoAnsiWidth = ${logoWidth};
export const sableLogoAnsiHeight = ${rows.length};
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, contents);

async function findContentBounds(filePath) {
  const { data: sourceData, info: sourceInfo } = await sharp(filePath)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let minX = sourceInfo.width;
  let minY = sourceInfo.height;
  let maxX = -1;
  let maxY = -1;

  for (let y = 0; y < sourceInfo.height; y += 1) {
    for (let x = 0; x < sourceInfo.width; x += 1) {
      const offset = (y * sourceInfo.width + x) * sourceInfo.channels;
      const luma = (0.2126 * sourceData[offset])
        + (0.7152 * sourceData[offset + 1])
        + (0.0722 * sourceData[offset + 2]);

      if (luma > contentLumaThreshold) {
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
    }
  }

  if (maxX < minX || maxY < minY) {
    return {
      left: 0,
      top: 0,
      width: sourceInfo.width,
      height: sourceInfo.height,
    };
  }

  const contentWidth = maxX - minX + 1;
  const contentHeight = maxY - minY + 1;
  const margin = Math.round(Math.max(contentWidth, contentHeight) * cropMarginRatio);
  const left = Math.max(0, minX - margin);
  const top = Math.max(0, minY - margin);
  const right = Math.min(sourceInfo.width - 1, maxX + margin);
  const bottom = Math.min(sourceInfo.height - 1, maxY + margin);

  return {
    left,
    top,
    width: right - left + 1,
    height: bottom - top + 1,
  };
}

function getPixel(x, y) {
  const offset = (y * info.width + x) * info.channels;

  return {
    r: data[offset],
    g: data[offset + 1],
    b: data[offset + 2],
    a: data[offset + 3],
  };
}

function renderBrailleCell(x, y) {
  const pixels = [
    getCellPixel(x, y),
    getCellPixel(x, y + 1),
    getCellPixel(x, y + 2),
    getCellPixel(x, y + 3),
    getCellPixel(x + 1, y),
    getCellPixel(x + 1, y + 1),
    getCellPixel(x + 1, y + 2),
    getCellPixel(x + 1, y + 3),
  ];
  const lumas = pixels.map(luma);
  const averageLuma = average(lumas);
  const threshold = Math.max(blockThreshold, averageLuma * 0.9);
  const mask = lumas.reduce((value, pixelLuma, index) => (
    pixelLuma >= threshold ? value | brailleDots[index] : value
  ), 0);
  const foregroundPixels = pixels.filter((_, index) => (mask & brailleDots[index]) !== 0);

  if (mask === 0) {
    return `${foreground(ansiPalette[0])}${background(ansiPalette[0])} `;
  }

  return `${foreground(nearestAnsiColor(averagePixel(foregroundPixels)))}${background(ansiPalette[0])}${String.fromCharCode(0x2800 + mask)}`;
}

function getCellPixel(x, y) {
  if (x >= info.width || y >= info.height) {
    return blackPixel;
  }

  return getPixel(x, y);
}

function averagePixel(pixels) {
  return {
    r: Math.round(average(pixels.map((pixel) => pixel.r))),
    g: Math.round(average(pixels.map((pixel) => pixel.g))),
    b: Math.round(average(pixels.map((pixel) => pixel.b))),
  };
}

function average(values) {
  return values.reduce((total, value) => total + value, 0) / values.length;
}

function nearestAnsiColor(pixel) {
  return ansiPalette.reduce((best, color) => {
    const distance = colorDistance(pixel, color);

    return distance < best.distance ? { color, distance } : best;
  }, { color: ansiPalette[0], distance: Number.POSITIVE_INFINITY }).color;
}

function colorDistance(left, right) {
  return ((left.r - right.r) ** 2) + ((left.g - right.g) ** 2) + ((left.b - right.b) ** 2);
}

function luma(pixel) {
  return (0.2126 * pixel.r) + (0.7152 * pixel.g) + (0.0722 * pixel.b);
}

function foreground(color) {
  return `\x1b[${color.foreground}m`;
}

function background(color) {
  return `\x1b[${color.background}m`;
}
